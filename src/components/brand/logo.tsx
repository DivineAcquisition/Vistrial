/**
 * Vector lockup of the Vistrial crest + wordmark. Kept as glyph outlines
 * rather than live text so the logo never depends on a webfont loading,
 * and stays sharp at any size or pixel density.
 */
export default function Logo({
  className,
  markOnly = false,
  tone = 'silver',
  title = 'Vistrial',
}: LogoProps) {
  const gradientId = `${useId()}-logo`;
  const fill = tone === 'silver' ? `url(#${gradientId})` : 'currentColor';

  return (
    <svg
      viewBox={markOnly ? '0 0 160 184' : '0 0 366.85 58'}
      role="img"
      aria-label={title}
      className={className}
    >
      {tone === 'silver' && (
        <defs>
          <linearGradient id={gradientId} x1="0" y1="0" x2="0.15" y2="1">
            <stop offset="0%" stopColor="#ffffff" />
            <stop offset="45%" stopColor="#eeecf8" />
            <stop offset="100%" stopColor="#b3b1c6" />
          </linearGradient>
        </defs>
      )}
      {markOnly ? (
        <path fill={fill} d={MARK_PATH} />
      ) : (
        <g fill={fill}>
          <g transform="scale(0.315217)">
            <path d={MARK_PATH} />
          </g>
          <g transform="translate(63.43 2.07)">
            <path d={WORDMARK_PATH} />
          </g>
        </g>
      )}
    </svg>
  );
}
